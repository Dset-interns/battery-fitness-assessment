"""Request and response shapes. These are the contract in openapi.json."""

from __future__ import annotations

import datetime as dt
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

TestKey = Literal["height", "weight", "sit_and_reach", "vertical_jump", "broad_jump", "medicine_ball_throw",
                  "sprint_30m", "shuttle_run", "sit_ups", "endurance_run"]
Confidence = Literal["GREEN", "AMBER", "RED"]


class ConsentItems(BaseModel):
    assess: bool = Field(description="Taking part in the assessment and recording the results")
    video: bool = Field(description="Video and photo kept on the assessor's phone for audit, not uploaded to a commercial cloud")
    data: bool = Field(description="Sharing de-identified results with SAI and NeGD, and with the athlete, guardian and school")
    parent_height: bool = Field(False, description="Optional: parental height recorded")


class ConsentIn(BaseModel):
    version: int = 1
    signed_at: dt.datetime
    signer_name: str = Field(min_length=2, max_length=160)
    relationship: Literal["self", "parent", "guardian"]
    minor: bool
    items: ConsentItems
    assessor: str = Field("", max_length=120)
    signature_png_base64: str | None = Field(None, description="The drawn signature, PNG, base64", max_length=400_000)


class AthleteIn(BaseModel):
    local_id: str = Field(min_length=1, max_length=40, description="The app's own id for the athlete on that phone")
    name: str = Field(min_length=1, max_length=160)
    age_years: int = Field(ge=5, le=25, description="Age at registration; 12 and over follows the 12+ rules (ruling C30)")
    gender: Literal["F", "M", "O"]
    school: str = Field("", max_length=200)
    id_type: Literal["APAAR", "AADHAAR", "NSRS", "LOCAL"] = "LOCAL"
    id_number: str = Field("", max_length=40)
    assessment_date: dt.date
    mother_cm: int | None = Field(None, ge=50, le=250)
    mother_source: Literal["measured", "self", ""] = ""
    father_cm: int | None = Field(None, ge=50, le=250)
    father_source: Literal["measured", "self", ""] = ""
    consent: ConsentIn


class AuditItem(BaseModel):
    model_config = ConfigDict(extra="allow")
    label: str = ""
    detail: str = ""
    valid: bool | None = None


class VideoMeta(BaseModel):
    key: str = Field(max_length=120)
    duration_s: float | None = None
    size_bytes: int | None = None
    declaration: dict | None = Field(None, description="Athlete and coach authenticity declaration (ruling C43)")


class AttemptIn(BaseModel):
    attempt_id: str = Field(max_length=120, description="Stable id: the video key, or test:n when there is no video")
    attempt_no: int = Field(ge=1)
    valid: bool
    value: float | None = None
    unit: str = Field("", max_length=10)
    confidence: Confidence
    method: str = ""
    audit: list[AuditItem] = []
    video: VideoMeta | None = None


class ResultIn(BaseModel):
    athlete_local_id: str
    test_key: TestKey
    attempts: list[AttemptIn] = Field(max_length=12)


class SyncBatch(BaseModel):
    device_id: str = Field(min_length=8, max_length=64, description="Generated by the app on first run")
    assessor: str = Field("", max_length=120)
    app_version: str = Field("", max_length=32)
    sent_at: dt.datetime
    athletes: list[AthleteIn]
    results: list[ResultIn] = []


class Rejected(BaseModel):
    local_id: str
    reason: str


class SyncResponse(BaseModel):
    server_time: dt.datetime
    accepted_athletes: int
    attempts_upserted: int
    results_upserted: int
    rejected: list[Rejected]
    athlete_uids: dict[str, str] = Field(description="local_id to server athlete uid, used for media uploads")


class MediaOut(BaseModel):
    key: str
    kind: Literal["video", "photo"]
    size_bytes: int
    sha256: str
    retain_until: dt.datetime | None


class DeidResultOut(BaseModel):
    test_key: str
    status: str
    best_value: float | None
    unit: str
    confidence: str
    attempts_count: int


class DeidSubjectOut(BaseModel):
    pseudonym: str
    age_years: int
    age_band: str
    gender: str
    assessment_month: str
    mother_cm: int | None = None
    father_cm: int | None = None
    results: list[DeidResultOut]


class DeidPage(BaseModel):
    total: int
    limit: int
    offset: int
    subjects: list[DeidSubjectOut]


class Stats(BaseModel):
    devices: int
    athletes: int
    attempts: int
    media_files: int
    deidentified_subjects: int


class Health(BaseModel):
    status: Literal["ok"]
    version: str
    database: Literal["up"]


class ServerConfig(BaseModel):
    version: str
    max_batch_athletes: int
    max_media_mb: int
    retention_days: int = Field(description="0 means kept until purged by hand")
    consent_version: int
