"""
Database schema.

Two zones, kept apart on purpose:

* IDENTIFIED zone (tables without a prefix): who the athlete is, the signed consent, every attempt, and the media
  index. Reachable only with the admin scope. This is what audit and withdrawal of consent need.
* DE-IDENTIFIED zone (tables prefixed deid_): what the programme analyses. A pseudonym instead of a name, an age
  band, no school, no ID number, no free text. Reachable with the export scope. Nothing in this zone can be joined
  back to a person without the pseudonym secret, which lives only in the gateway's configuration.

In PostgreSQL the two zones are best given separate schemas and separate database roles; see README.md.
"""

from __future__ import annotations

import datetime as dt

from sqlalchemy import (JSON, Boolean, Date, DateTime, Float, ForeignKey, Index, Integer, LargeBinary, String,
                        Text, UniqueConstraint)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship


def utcnow() -> dt.datetime:
    return dt.datetime.now(dt.timezone.utc)


class Base(DeclarativeBase):
    pass


# --------------------------------------------------------------------------------------------- identified zone
class Device(Base):
    __tablename__ = "devices"
    id: Mapped[str] = mapped_column(String(64), primary_key=True)          # generated by the app on first run
    assessor: Mapped[str] = mapped_column(String(120), default="")
    app_version: Mapped[str] = mapped_column(String(32), default="")
    first_seen: Mapped[dt.datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    last_seen: Mapped[dt.datetime] = mapped_column(DateTime(timezone=True), default=utcnow)


class Athlete(Base):
    __tablename__ = "athletes"
    uid: Mapped[str] = mapped_column(String(36), primary_key=True)          # uuid5 of (device, local id)
    device_id: Mapped[str] = mapped_column(ForeignKey("devices.id"), index=True)
    local_id: Mapped[str] = mapped_column(String(40))
    pseudonym: Mapped[str] = mapped_column(String(32), index=True)       # not unique: one person can be on several phones
    name: Mapped[str] = mapped_column(String(160))
    age_years: Mapped[int] = mapped_column(Integer)                          # fixed at registration (ruling C30)
    gender: Mapped[str] = mapped_column(String(1))
    school: Mapped[str] = mapped_column(String(200), default="")
    id_type: Mapped[str] = mapped_column(String(10), default="LOCAL")
    id_number: Mapped[str] = mapped_column(String(40), default="")
    assessment_date: Mapped[dt.date] = mapped_column(Date)
    mother_cm: Mapped[int | None] = mapped_column(Integer, nullable=True)
    mother_source: Mapped[str] = mapped_column(String(16), default="")
    father_cm: Mapped[int | None] = mapped_column(Integer, nullable=True)
    father_source: Mapped[str] = mapped_column(String(16), default="")
    created_at: Mapped[dt.datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    updated_at: Mapped[dt.datetime] = mapped_column(DateTime(timezone=True), default=utcnow, onupdate=utcnow)
    consents: Mapped[list["Consent"]] = relationship(back_populates="athlete", cascade="all, delete-orphan")
    attempts: Mapped[list["Attempt"]] = relationship(back_populates="athlete", cascade="all, delete-orphan")
    results: Mapped[list["Result"]] = relationship(back_populates="athlete", cascade="all, delete-orphan")
    media: Mapped[list["Media"]] = relationship(back_populates="athlete", cascade="all, delete-orphan")
    __table_args__ = (UniqueConstraint("device_id", "local_id", name="uq_athlete_device_local"),)


class Consent(Base):
    __tablename__ = "consents"
    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    athlete_uid: Mapped[str] = mapped_column(ForeignKey("athletes.uid", ondelete="CASCADE"), index=True)
    version: Mapped[int] = mapped_column(Integer, default=1)
    signed_at: Mapped[dt.datetime] = mapped_column(DateTime(timezone=True))
    signer_name: Mapped[str] = mapped_column(String(160))
    relationship_: Mapped[str] = mapped_column("relationship", String(10))   # self | parent | guardian
    minor: Mapped[bool] = mapped_column(Boolean)
    item_assess: Mapped[bool] = mapped_column(Boolean)
    item_video: Mapped[bool] = mapped_column(Boolean)
    item_data: Mapped[bool] = mapped_column(Boolean)
    item_parent_height: Mapped[bool] = mapped_column(Boolean, default=False)
    assessor: Mapped[str] = mapped_column(String(120), default="")
    signature_png: Mapped[bytes | None] = mapped_column(LargeBinary, nullable=True)
    received_at: Mapped[dt.datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    athlete: Mapped[Athlete] = relationship(back_populates="consents")
    __table_args__ = (UniqueConstraint("athlete_uid", "signed_at", name="uq_consent_athlete_time"),)


class Attempt(Base):
    __tablename__ = "attempts"
    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    athlete_uid: Mapped[str] = mapped_column(ForeignKey("athletes.uid", ondelete="CASCADE"), index=True)
    test_key: Mapped[str] = mapped_column(String(32))
    attempt_id: Mapped[str] = mapped_column(String(120))                      # the app's id: the video key, or test:n
    attempt_no: Mapped[int] = mapped_column(Integer)
    valid: Mapped[bool] = mapped_column(Boolean)
    value: Mapped[float | None] = mapped_column(Float, nullable=True)
    unit: Mapped[str] = mapped_column(String(10), default="")
    confidence: Mapped[str] = mapped_column(String(5))                       # GREEN | AMBER | RED
    method: Mapped[str] = mapped_column(Text, default="")
    audit: Mapped[list] = mapped_column(JSON, default=list)                  # rule audit: fouls, rejected reps, splits
    video_key: Mapped[str | None] = mapped_column(String(120), nullable=True)
    video_duration_s: Mapped[float | None] = mapped_column(Float, nullable=True)
    video_size_bytes: Mapped[int | None] = mapped_column(Integer, nullable=True)
    declaration: Mapped[dict | None] = mapped_column(JSON, nullable=True)    # athlete and coach authenticity declaration
    received_at: Mapped[dt.datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    athlete: Mapped[Athlete] = relationship(back_populates="attempts")
    __table_args__ = (UniqueConstraint("athlete_uid", "test_key", "attempt_id", name="uq_attempt"),
                      Index("ix_attempt_athlete_test", "athlete_uid", "test_key"))


class Result(Base):
    """The score that counts for a test, derived from its attempts by the rule for that test."""
    __tablename__ = "results"
    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    athlete_uid: Mapped[str] = mapped_column(ForeignKey("athletes.uid", ondelete="CASCADE"), index=True)
    test_key: Mapped[str] = mapped_column(String(32))
    status: Mapped[str] = mapped_column(String(10))                           # recorded | rejected
    best_value: Mapped[float | None] = mapped_column(Float, nullable=True)
    unit: Mapped[str] = mapped_column(String(10), default="")
    confidence: Mapped[str] = mapped_column(String(5), default="RED")
    attempts_count: Mapped[int] = mapped_column(Integer, default=0)
    updated_at: Mapped[dt.datetime] = mapped_column(DateTime(timezone=True), default=utcnow, onupdate=utcnow)
    athlete: Mapped[Athlete] = relationship(back_populates="results")
    __table_args__ = (UniqueConstraint("athlete_uid", "test_key", name="uq_result"),)


class Media(Base):
    """Index of the videos and photos kept for audit (rulings C23, C36, C42). The files live in object storage or MEDIA_DIR."""
    __tablename__ = "media"
    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    athlete_uid: Mapped[str] = mapped_column(ForeignKey("athletes.uid", ondelete="CASCADE"), index=True)
    test_key: Mapped[str] = mapped_column(String(32))
    attempt_id: Mapped[str | None] = mapped_column(String(120), nullable=True)
    kind: Mapped[str] = mapped_column(String(10))                             # video | photo
    key: Mapped[str] = mapped_column(String(120))
    mime: Mapped[str] = mapped_column(String(60), default="")
    size_bytes: Mapped[int] = mapped_column(Integer)
    sha256: Mapped[str] = mapped_column(String(64))
    path: Mapped[str] = mapped_column(Text)
    uploaded_at: Mapped[dt.datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    retain_until: Mapped[dt.datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    athlete: Mapped[Athlete] = relationship(back_populates="media")
    __table_args__ = (UniqueConstraint("athlete_uid", "key", name="uq_media"),)


class SyncLog(Base):
    __tablename__ = "sync_log"
    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    device_id: Mapped[str] = mapped_column(String(64), index=True)
    received_at: Mapped[dt.datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    athletes_accepted: Mapped[int] = mapped_column(Integer, default=0)
    athletes_rejected: Mapped[int] = mapped_column(Integer, default=0)
    attempts_upserted: Mapped[int] = mapped_column(Integer, default=0)


# ------------------------------------------------------------------------------------------ de-identified zone
class DeidSubject(Base):
    __tablename__ = "deid_subjects"
    pseudonym: Mapped[str] = mapped_column(String(32), primary_key=True)
    age_years: Mapped[int] = mapped_column(Integer)
    age_band: Mapped[str] = mapped_column(String(8))
    gender: Mapped[str] = mapped_column(String(1))
    assessment_month: Mapped[str] = mapped_column(String(7))                  # YYYY-MM, not the day
    mother_cm: Mapped[int | None] = mapped_column(Integer, nullable=True)    # only with the optional consent
    father_cm: Mapped[int | None] = mapped_column(Integer, nullable=True)
    updated_at: Mapped[dt.datetime] = mapped_column(DateTime(timezone=True), default=utcnow, onupdate=utcnow)


class DeidResult(Base):
    __tablename__ = "deid_results"
    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    pseudonym: Mapped[str] = mapped_column(ForeignKey("deid_subjects.pseudonym", ondelete="CASCADE"), index=True)
    test_key: Mapped[str] = mapped_column(String(32))
    status: Mapped[str] = mapped_column(String(10))
    best_value: Mapped[float | None] = mapped_column(Float, nullable=True)
    unit: Mapped[str] = mapped_column(String(10), default="")
    confidence: Mapped[str] = mapped_column(String(5), default="RED")
    attempts_count: Mapped[int] = mapped_column(Integer, default=0)
    __table_args__ = (UniqueConstraint("pseudonym", "test_key", name="uq_deid_result"),)
